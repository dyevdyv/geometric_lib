def area(a, b): 
    '''Принимает длины сторон прямоугольника, возвращает его площадь'''
    return a * b 

def perimeter(a, b): 
    '''
    По полученным длинам сторон прямоугольника вычисляет его периметр.
    
    Параметры:
        a (int): длина одной сторона
        b (int): длина второй, смежной с первой, стороны
    Возвращаемое значение:
        perimeter(a, b): периметр прямоугольника со сторонами a и b
    '''
    return 2 * (a + b) 
